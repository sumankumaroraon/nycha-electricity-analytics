"""Run the SQL layer in DuckDB, execute validation tests and reconcile against Python outputs.

Usage (from the repository root, after running the Python pipeline):

    python scripts/run_sql.py

Writes data/interim/nycha_energy.duckdb and reports/sql_validation_results.md.
Exits with a non-zero status if any test or reconciliation check fails.
"""
from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from nycha_energy import config  # noqa: E402

BUILD = [
    "01_load_raw.sql", "02_stg_bills.sql", "03_int_bills_deduplicated.sql",
    "04_int_bills_flagged.sql", "05_fct_development_month.sql", "06_mart_metrics_and_drivers.sql",
]


def main() -> int:
    db_path = config.DATA_INTERIM / "nycha_energy.duckdb"
    db_path.parent.mkdir(parents=True, exist_ok=True)
    if db_path.exists():
        db_path.unlink()
    con = duckdb.connect(str(db_path))
    con.execute(f"SET VARIABLE raw_csv = '{config.RAW_CSV.as_posix()}'")
    con.execute(f"SET VARIABLE start_year = {config.START_YEAR}")
    end = config.END_YEAR_OVERRIDE
    con.execute(f"SET VARIABLE end_year = {int(end) if end else 'NULL'}::INTEGER")
    con.execute(f"SET VARIABLE processed_dir = '{config.DATA_PROCESSED.as_posix()}'")

    for name in BUILD:
        # Single thread while landing the raw file so record_id follows file order.
        con.execute("SET threads = 1" if name == "01_load_raw.sql" else "RESET threads")
        con.execute((config.SQL_DIR / name).read_text())
        print(f"  built  {name}")

    tests = con.execute((config.SQL_DIR / "07_validation_tests.sql").read_text()).df()
    recon = con.execute((config.SQL_DIR / "08_reconcile_with_python.sql").read_text()).df()
    tests["status"] = tests["failures"].map(lambda n: "PASS" if n == 0 else "FAIL")
    recon["status"] = recon["mismatches"].map(lambda n: "PASS" if n == 0 else "FAIL")

    counts = con.execute("""
        SELECT (SELECT count(*) FROM raw_bills) AS raw_rows,
               (SELECT count(*) FROM int_window_bills) AS window_rows,
               (SELECT count(*) FROM int_exclusion_log) AS excluded_rows,
               (SELECT count(*) FROM int_bills_flagged) AS retained_rows,
               (SELECT count(*) FROM fct_development_month) AS fact_rows,
               (SELECT end_year FROM analysis_window) AS end_year
    """).df().iloc[0]

    def table(df, cols):
        lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
        lines += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for _, r in df.iterrows()]
        return "\n".join(lines)

    report = f"""# SQL validation results

_Generated by `scripts/run_sql.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}._

The SQL layer (`sql/01`–`06`) re-implements the cleaning, aggregation and decomposition rules
independently of Python. `07` tests internal consistency; `08` reconciles SQL with Python outputs.

| Item | Value |
|---|---|
| Raw rows | {counts.raw_rows:,} |
| Rows in analysis window | {counts.window_rows:,} |
| Excluded rows | {counts.excluded_rows:,} |
| Retained rows | {counts.retained_rows:,} |
| Development-month rows | {counts.fact_rows:,} |
| Last complete year | {counts.end_year} |

## Validation tests

{table(tests, ["test_id", "description", "failures", "status"])}

## Python ↔ SQL reconciliation

{table(recon, ["check_id", "description", "mismatches", "status"])}
"""
    (config.REPORTS / "sql_validation_results.md").write_text(report)
    print(tests.to_string(index=False))
    print(recon.to_string(index=False))
    ok = (tests["failures"] == 0).all() and (recon["mismatches"] == 0).all()
    print("\nALL CHECKS PASSED" if ok else "\nCHECKS FAILED — see reports/sql_validation_results.md")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
